package screenscmd

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/meta-ui-labs/cuppa/libs/cuppafile/disk"
	"github.com/meta-ui-labs/cuppa/libs/document/design"
)

// A design that says where its Go source goes is exported there with no
// arguments, relative to its own file, and checked the same way.
func TestADesignExportsToTheFolderItSaved(t *testing.T) {
	dir := t.TempDir()
	doc := design.NewDocument("App", 60, 12)
	doc.Add(design.Node{Component: "lipgloss.box", Name: "Frame", Rect: design.Rect{X: 1, Y: 1, W: 20, H: 4}})
	doc.Pages = []design.Page{{Name: "Setup", Folder: "setup/prefs"}, {Name: "Run"}}
	doc.Export = design.ExportSettings{Layout: design.ExportSlices, Library: true, Dir: "libs/core", Module: "example.com/core"}
	if err := os.MkdirAll(filepath.Join(dir, "designs"), 0o755); err != nil {
		t.Fatal(err)
	}
	file, err := disk.Save(filepath.Join(dir, "designs", "app"), doc)
	if err != nil {
		t.Fatal(err)
	}
	var stdout, stderr bytes.Buffer
	if code := Run([]string{file}, &stdout, &stderr); code != 0 {
		t.Fatalf("exit %d: %s%s", code, stdout.String(), stderr.String())
	}
	for _, want := range []string{"libs/core/setup/prefs/prefs.cuppa.go", "libs/core/pages/run/run.cuppa.go", "libs/core/internal/cuppa/runtime.go"} {
		if _, err := os.Stat(filepath.Join(dir, "designs", filepath.FromSlash(want))); err != nil {
			t.Errorf("missing %s", want)
		}
	}
	stdout.Reset()
	if code := Run([]string{file, "--check"}, &stdout, &stderr); code != 0 || !strings.Contains(stdout.String(), "is current") {
		t.Fatalf("check: exit %d: %s%s", code, stdout.String(), stderr.String())
	}
	page := filepath.Join(dir, "designs", "libs", "core", "setup", "prefs", "prefs.cuppa.go")
	if err := os.WriteFile(page, []byte("// Code generated by Cuppa. DO NOT EDIT.\n\npackage prefs\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	stdout.Reset()
	if code := Run([]string{file, "--check"}, &stdout, &stderr); code != 1 || !strings.Contains(stdout.String(), "prefs.cuppa.go") {
		t.Fatalf("check of an edited file: exit %d: %s%s", code, stdout.String(), stderr.String())
	}
}
