package format

import (
	"encoding/base64"
	"errors"
	"testing"

	"github.com/meta-tui/cuppa/libs/document/design"
)

func TestADesignComesBackOutOfTheGoSource(t *testing.T) {
	doc := design.NewDocument("App", 80, 24)
	doc.Add(design.Node{Component: "lipgloss.box", Name: "Frame", Rect: design.Rect{W: 20, H: 5}})
	doc.Pages = []design.Page{{Name: "Home"}, {Name: "Settings"}}
	data, err := Encode(doc)
	if err != nil {
		t.Fatal(err)
	}
	src := "// Code generated by Cuppa. DO NOT EDIT.\n\n" + GoDirective + base64.StdEncoding.EncodeToString(data) + "\n\npackage main\n"
	got, err := FromGo([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if got.Name != "App" || len(got.Pages) != 2 || len(got.Nodes) != 1 {
		t.Fatalf("got %+v", got)
	}
	if _, err := FromGo([]byte("package main\n")); !errors.Is(err, ErrNoDesign) {
		t.Errorf("no design: %v", err)
	}
	if _, err := FromGo([]byte(GoDirective + "!!!\n")); !errors.Is(err, ErrCorrupt) {
		t.Errorf("bad data: %v", err)
	}
}
