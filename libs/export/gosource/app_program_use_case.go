package gosource

import (
	"fmt"
	"strings"

	"github.com/meta-ui-labs/cuppa/libs/document/design"
)

// generateApp is the program of a design with pages: every page a screen of
// package main, the router, and the main.go that runs them.
func generateApp(doc design.Document, cat Catalog, opts Options) Project {
	p := GenerateScreensWith([]design.Document{doc}, cat, "main", opts)
	p.Module = Slug(doc.Name)
	p.Files["go.mod"] = goMod(p.Module, p.Requires)
	p.Files["main.go"] = tidy(mainSource(doc, doc.Screens()), &p)
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\nA Bubble Tea v2 application generated by Cuppa, one screen per page.\n\n", doc.Name)
	b.WriteString("```sh\ngo mod tidy\ngo run .\n```\n\n")
	b.WriteString("Pages: " + strings.Join(screenNames(doc), ", ") + ". Tabs, panels and the components that go to a page work with no code of yours.\n\n")
	b.WriteString("- `" + snake(doc.Name) + "_app.go` is the router: the props of every page, which one is shown and `Handle`.\n")
	b.WriteString("- `<page>_screen_contract.go` and `<page>_screen_view.go` are the pages; `cuppa_*.go` is the runtime they share.\n")
	b.WriteString("- `main.go` is the program that runs them. Cuppa opens the design again from it: `cuppa main.go`.\n")
	if len(p.Notes) > 0 {
		b.WriteString("\n## Not generated yet\n\n")
		for _, n := range p.Notes {
			b.WriteString("- " + n + "\n")
		}
	}
	p.Files["README.md"] = b.String()
	return p
}

// screenNames are the names of the design's screens: its pages, without the
// master.
func screenNames(doc design.Document) []string {
	var out []string
	for _, s := range doc.Screens() {
		out = append(out, s.Name)
	}
	return out
}
