// --check writes nothing: it passes while the package is what the designs
// export and fails, listing the files, when it is not.
func TestCheckSaysWhetherThePackageIsCurrent(t *testing.T) {
	dir := t.TempDir()
	designs := filepath.Join(dir, "designs")
	if err := os.MkdirAll(designs, 0o755); err != nil {
		t.Fatal(err)
	}
	doc := design.NewDocument("Hello", 20, 3)
	doc.Add(design.Node{Component: "lipgloss.label", Name: "Title", Rect: design.Rect{W: 10, H: 1}, Props: map[string]string{"text": "Hi"}, Bind: map[string]string{"text": "Title"}})
	if _, err := disk.Save(filepath.Join(designs, "hello.cuppa"), doc); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "screens")
	var o, e bytes.Buffer
	if code := Run([]string{designs, "-o", out, "-p", "screens", "--check"}, &o, &e); code != 1 {
		t.Fatalf("an empty folder is not current: exit %d\n%s%s", code, o.String(), e.String())
	}
	if !strings.Contains(o.String(), "missing") {
		t.Errorf("missing files are not listed:\n%s", o.String())
	}
	if _, err := os.Stat(out); err == nil {
		t.Error("--check created the folder")
	}
	if code := Run([]string{designs, "-o", out, "-p", "screens"}, &o, &e); code != 0 {
		t.Fatalf("export: %d %s", code, e.String())
	}
	o.Reset()
	if code := Run([]string{designs, "-o", out, "-p", "screens", "--check"}, &o, &e); code != 0 || !strings.Contains(o.String(), "current") {
		t.Fatalf("just exported: exit %d\n%s%s", code, o.String(), e.String())
	}
	// A change of the design, and a stale generated file.
	doc.Nodes[0].Props["text"] = "Hello"
	doc.Nodes[0].Bind["text"] = "Greeting"
	if _, err := disk.Save(filepath.Join(designs, "hello.cuppa"), doc); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(out, "old_screen_view.go")
	if err := os.WriteFile(stale, []byte("// Code generated by Cuppa. DO NOT EDIT.\n\npackage screens\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	o.Reset()
	if code := Run([]string{designs, "-o", out, "-p", "screens", "--check"}, &o, &e); code != 1 {
		t.Fatalf("a changed design: exit %d\n%s", code, o.String())
	}
	for _, want := range []string{"hello_screen_contract.go: differs", "old_screen_view.go: generated for a screen that is no longer designed"} {
		if !strings.Contains(o.String(), want) {
			t.Errorf("%q missing:\n%s", want, o.String())
		}
	}
}
